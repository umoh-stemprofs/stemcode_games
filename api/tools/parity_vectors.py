"""Generate the shared rule-parity vectors (P9-T03).

The offline ports in ``web/lib/games/rules`` must decide exactly what the Python
domain decides: an offline batch is re-scored on the server by replaying it, so
a single point of drift turns a learner's honest answers into zeros. The two
implementations therefore both read one committed JSON file, and this script is
the only thing that writes it.

Run it after changing a rule in ``app/games/domain``::

    node scripts/py.mjs api/tools/parity_vectors.py

The file is deliberately generated by the Python side. It is the reference
implementation, and CI fails when either language stops matching it.
"""

from __future__ import annotations

import datetime as dt
import json
import random
from pathlib import Path

from app.games.domain import guessing
from app.games.domain import wordscramble as ws

ROOT = Path(__file__).resolve().parents[2]
TARGET = ROOT / "shared" / "parity" / "game-rules.json"


def _seed_text(seed: int) -> str:
    """A seed as JSON-safe text: 63-bit seeds do not fit a JSON number exactly."""
    return str(seed)


def _uint32_stream(seed: int | str, count: int) -> list[int]:
    rng = random.Random(seed)
    return [rng.getrandbits(32) for _ in range(count)]


def _shuffle(seed: int, values: list[str]) -> list[str]:
    rng = random.Random(seed)
    shuffled = list(values)
    rng.shuffle(shuffled)
    return shuffled


def _sample(seed: int, n: int, k: int) -> list[int]:
    rng = random.Random(seed)
    return rng.sample(range(n), k)


def _item(index: int) -> ws.Item:
    """A deterministic, unique answer so a vector file stays readable."""
    answer = (
        f"word{chr(97 + index % 26)}{chr(97 + (index // 26) % 26)}{chr(97 + (index // 676) % 26)}"
    )
    return ws.Item(
        id=f"item-{index:03d}",
        answer=answer,
        alt_answers=(),
        clue=f"Clue {index}",
        clue_image_key=None,
        clue_audio_key=None,
        difficulty=1,
    )


def _build_rounds(seed: int, items: list[ws.Item]) -> list[dict[str, object]]:
    rounds = ws.build_rounds(items, random.Random(seed))
    return [
        {
            "item_id": str(round_["item_id"]),
            "letters": str(round_["letters"]),
            "clue": round_["clue"],
        }
        for round_ in rounds
    ]


def _deadline_ms(started_at: dt.datetime) -> int:
    return int(started_at.timestamp() * 1000)


def _deadline_plus(deadline_at: dt.datetime, offset_ms: int) -> int:
    return _deadline_ms(deadline_at) + offset_ms


def word_scramble_vectors() -> dict[str, object]:
    scoring = [
        {"elapsed_seconds": 0, "used_hint": False, "attempt": 1, "time_bonus": 5, "score": 15},
        {"elapsed_seconds": 0, "used_hint": False, "attempt": 2, "time_bonus": 5, "score": 7},
        {"elapsed_seconds": 0, "used_hint": True, "attempt": 1, "time_bonus": 5, "score": 12},
        {"elapsed_seconds": 4.5, "used_hint": False, "attempt": 1, "time_bonus": 4, "score": 14},
        {"elapsed_seconds": 22.4, "used_hint": False, "attempt": 1, "time_bonus": 2, "score": 12},
        {"elapsed_seconds": 22.4, "used_hint": True, "attempt": 2, "time_bonus": 2, "score": 4},
        {"elapsed_seconds": 44.9, "used_hint": False, "attempt": 1, "time_bonus": 0, "score": 10},
        {"elapsed_seconds": 45, "used_hint": False, "attempt": 1, "time_bonus": 0, "score": 10},
        {"elapsed_seconds": 120, "used_hint": False, "attempt": 1, "time_bonus": 0, "score": 10},
        {"elapsed_seconds": -3, "used_hint": False, "attempt": 1, "time_bonus": 5, "score": 15},
        {"elapsed_seconds": 1, "used_hint": True, "attempt": 3, "time_bonus": 4, "score": 5},
    ]
    # The time bonus and the score are derived here from the same call the test
    # will make, so a stale hand-written expectation cannot creep in.
    for case in scoring:
        elapsed = float(case["elapsed_seconds"])
        case["time_bonus"] = ws.time_bonus(elapsed)
        case["score"] = ws.round_score(
            elapsed_seconds=elapsed,
            used_hint=bool(case["used_hint"]),
            attempt=int(case["attempt"]),
        )

    item = ws.Item(
        id="item-stone",
        answer="stone",
        alt_answers=("stoun", "Stones"),
        clue="Hard and grey.",
        clue_image_key="img/stone",
        clue_audio_key=None,
        difficulty=1,
    )
    correctness = [
        {"value": "stone", "correct": True},
        {"value": "  STONE ", "correct": True},
        {"value": "stoun", "correct": True},
        {"value": "stones", "correct": True},
        {"value": "stonee", "correct": False},
        {"value": "", "correct": False},
    ]
    for case in correctness:
        case["correct"] = ws.is_correct(item, str(case["value"]))

    small_items = [_item(index) for index in range(ws.MIN_ITEMS_PER_PACK)]
    large_items = [_item(index) for index in range(200)]

    started = dt.datetime(2026, 11, 17, 10, 0, tzinfo=dt.UTC)

    return {
        "constants": {
            "game_id": ws.GAME_ID,
            "rounds": ws.ROUNDS,
            "round_seconds": ws.ROUND_SECONDS,
            "deadline_grace_seconds": ws.DEADLINE_GRACE_SECONDS,
            "max_attempts": ws.MAX_ATTEMPTS,
            "hint_cost": ws.HINT_COST,
            "base_points": ws.BASE_POINTS,
            "max_time_bonus": ws.MAX_TIME_BONUS,
            "min_items_per_pack": ws.MIN_ITEMS_PER_PACK,
        },
        "time_bonus": [
            {"elapsed_seconds": case["elapsed_seconds"], "bonus": case["time_bonus"]}
            for case in scoring
        ],
        "round_score": scoring,
        "correctness": correctness,
        "revelation": [
            {"answer": "stone", "first": ws.revelation("stone")},
            {"answer": "Algebra", "first": ws.revelation("Algebra")},
            {"answer": "", "first": ws.revelation("")},
        ],
        "scramble": [
            {"seed": 1, "answer": "planet", "letters": ws.scramble("planet", random.Random(1))},
            {"seed": 42, "answer": "stone", "letters": ws.scramble("stone", random.Random(42))},
            {
                "seed": 987654321,
                "answer": "algebra",
                "letters": ws.scramble("algebra", random.Random(987654321)),
            },
            {
                "seed": _seed_text(9223372036854775807),
                "answer": "computer",
                "letters": ws.scramble("computer", random.Random(9223372036854775807)),
            },
        ],
        "build_rounds": [
            {
                "name": "pack_of_fifteen_pooled",
                "seed": 2026,
                "items": [
                    {
                        "id": entry.id,
                        "answer": entry.answer,
                        "alt_answers": list(entry.alt_answers),
                        "clue": entry.clue,
                        "clue_image_key": entry.clue_image_key,
                        "clue_audio_key": entry.clue_audio_key,
                        "difficulty": entry.difficulty,
                    }
                    for entry in small_items
                ],
                "expected": _build_rounds(2026, small_items),
            },
            {
                "name": "pack_of_two_hundred_set_selection",
                "seed": 7,
                "items": [
                    {
                        "id": entry.id,
                        "answer": entry.answer,
                        "alt_answers": list(entry.alt_answers),
                        "clue": entry.clue,
                        "clue_image_key": entry.clue_image_key,
                        "clue_audio_key": entry.clue_audio_key,
                        "difficulty": entry.difficulty,
                    }
                    for entry in large_items
                ],
                "expected": _build_rounds(7, large_items),
            },
        ],
        "deadline": [
            {
                "name": "start",
                "started_at": started.isoformat(),
                "deadline_ms": _deadline_ms(ws.deadline(started)),
            },
            {
                "name": "late_by_one_ms",
                "started_at": started.isoformat(),
                "now_ms": _deadline_plus(ws.deadline(started), 1),
                "is_late": True,
            },
            {
                "name": "exactly_on_deadline",
                "started_at": started.isoformat(),
                "now_ms": _deadline_plus(ws.deadline(started), 0),
                "is_late": False,
            },
        ],
    }


def number_guess_vectors() -> dict[str, object]:
    seeds = [0, 1, 42, 987654321, 9223372036854775807]
    secrets = [
        {
            "seed": _seed_text(seed),
            "difficulty": difficulty,
            "index": index,
            "secret": guessing.secret_for(seed, index, difficulty),
        }
        for seed in seeds
        for difficulty in (1, 2, 3)
        for index in (0, 1, 2, 3, 4)
    ]

    scores = [
        {
            "attempt": attempt,
            "tries": tries,
            "score": guessing.score_for(attempt=attempt, tries=tries),
        }
        for tries in (8, 9, 10)
        for attempt in range(1, tries + 1)
    ]

    levels = [
        {"difficulty": difficulty, "low": level.low, "high": level.high, "tries": level.tries}
        for difficulty, level in sorted(guessing.LEVELS.items())
    ]

    rounds_for = {str(difficulty): guessing.rounds_for(difficulty) for difficulty in (1, 2, 3)}

    narrow = []
    for low, high, guess, verdict in (
        (1, 50, 25, "higher"),
        (1, 50, 25, "lower"),
        (26, 50, 37, "higher"),
        (26, 50, 37, "lower"),
        (1, 50, 50, "lower"),
        (1, 50, 1, "higher"),
        (10, 10, 10, "correct"),
    ):
        narrowed_low, narrowed_high = guessing.narrow(low, high, guess, verdict)
        narrow.append(
            {
                "low": low,
                "high": high,
                "guess": guess,
                "feedback": verdict,
                "expected_low": narrowed_low,
                "expected_high": narrowed_high,
            }
        )

    compare = [
        {"secret": secret, "guess": guess, "verdict": guessing.compare(secret, guess)}
        for secret, guess in ((37, 37), (37, 1), (37, 50), (1, 2), (1000, 1), (1, 1000))
    ]

    in_range = [
        {
            "difficulty": difficulty,
            "value": value,
            "allowed": guessing.in_range(value, guessing.level_for(difficulty)),
        }
        for difficulty, value in (
            (1, 1),
            (1, 50),
            (1, 0),
            (1, 51),
            (2, 200),
            (2, 201),
            (3, 1000),
            (3, 1001),
        )
    ]

    feedback = [
        {"code": code, "sentence": guessing.feedback_sentence(code)}
        for code in (
            "higher",
            "lower",
            "correct",
            "repeat",
            "out_of_range",
            "hot",
            "warm",
            "cold",
            "freezing",
            "unknown",
        )
    ]

    # Heat is a rule the browser also owns (offline play), so every band edge is
    # checked on both sides: one unit inside and one unit outside each cut.
    heat = [
        {
            "difficulty": difficulty,
            "secret": secret,
            "guess": guess,
            "heat": guessing.heat_for(secret, guess, guessing.level_for(difficulty)),
        }
        for difficulty, secret, guess in (
            (3, 30, 30),
            (3, 30, 31),
            (3, 30, 29),
            (3, 30, 40),
            (3, 30, 50),
            (3, 500, 579),
            (3, 500, 580),
            (3, 500, 581),
            (3, 500, 749),
            (3, 500, 750),
            (3, 500, 751),
            (3, 500, 999),
            (3, 500, 1000),
            (1, 30, 33),
            (1, 30, 34),
            (1, 30, 40),
            (1, 30, 50),
            (2, 100, 105),
        )
    ]

    started = dt.datetime(2026, 11, 17, 10, 0, tzinfo=dt.UTC)

    return {
        "constants": {
            "game_id": guessing.GAME_ID,
            "rounds": guessing.ROUNDS,
            "round_seconds": guessing.ROUND_SECONDS,
            "deadline_grace_seconds": guessing.DEADLINE_GRACE_SECONDS,
            "min_solved": guessing.MIN_SOLVED,
            "max_points_per_number": guessing.MAX_POINTS_PER_NUMBER,
        },
        "levels": levels,
        "rounds_for": rounds_for,
        "secrets": secrets,
        "scores": scores,
        "compare": compare,
        "in_range": in_range,
        "narrow": narrow,
        "feedback": feedback,
        "heat": heat,
        "heat_difficulty": guessing.HEAT_DIFFICULTY,
        "deadline": [
            {
                "name": "start",
                "started_at": started.isoformat(),
                "deadline_ms": _deadline_ms(guessing.deadline(started)),
            },
            {
                "name": "late_by_one_ms",
                "started_at": started.isoformat(),
                "now_ms": _deadline_plus(guessing.deadline(started), 1),
                "is_late": True,
            },
            {
                "name": "exactly_on_deadline",
                "started_at": started.isoformat(),
                "now_ms": _deadline_plus(guessing.deadline(started), 0),
                "is_late": False,
            },
        ],
    }


def random_vectors() -> dict[str, object]:
    """The generator itself, pinned independently of either game.

    If these drift, every scramble and every secret drifts with them, and the
    game-level vectors alone would be a much harder thing to debug.
    """
    seed = 1234567890123456789
    text_seed = f"{seed}:3"
    return {
        "int_seed_stream": {
            "seed": _seed_text(seed),
            "values": _uint32_stream(seed, 16),
        },
        "text_seed_stream": {
            "seed": text_seed,
            "values": _uint32_stream(text_seed, 16),
        },
        "shuffle": [
            {
                "seed": 99,
                "values": ["a", "b", "c", "d", "e", "f", "g"],
                "expected": _shuffle(99, ["a", "b", "c", "d", "e", "f", "g"]),
            },
            {
                "seed": 2026,
                "values": ["a", "b", "c", "d", "e", "f", "g"],
                "expected": _shuffle(2026, ["a", "b", "c", "d", "e", "f", "g"]),
            },
        ],
        "sample": [
            {"seed": 2026, "n": 15, "k": 10, "expected": _sample(2026, 15, 10)},
            {"seed": 7, "n": 200, "k": 10, "expected": _sample(7, 200, 10)},
        ],
    }


def main() -> None:
    payload = {
        "note": (
            "Generated by api/tools/parity_vectors.py from the Python domain rules. "
            "Do not edit by hand: change the rule, then regenerate."
        ),
        "random": random_vectors(),
        "word_scramble": word_scramble_vectors(),
        "number_guess": number_guess_vectors(),
    }
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text(json.dumps(payload, indent=2) + "\n", encoding="utf-8")
    print(f"wrote {TARGET.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
