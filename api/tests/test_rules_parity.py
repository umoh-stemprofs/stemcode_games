"""Rule parity: the Python rules against the shared vectors (P9-T03).

The offline TypeScript ports read the same file, so this test and its Vitest
counterpart are what keep the server and the phone deciding the same thing.
Vectors are generated by ``api/tools/parity_vectors.py``; when a rule changes,
regenerate them and make the port match.
"""

from __future__ import annotations

import datetime as dt
import json
import random
from pathlib import Path

from app.games.domain import guessing
from app.games.domain import wordscramble as ws

ROOT = Path(__file__).resolve().parents[2]
VECTORS = json.loads((ROOT / "shared" / "parity" / "game-rules.json").read_text(encoding="utf-8"))


def test_the_generator_matches_cpython() -> None:
    """Pin MT19937 and the two seeding rules before anything is built on them."""
    int_case = VECTORS["random"]["int_seed_stream"]
    rng = random.Random(int(int_case["seed"]))
    assert [rng.getrandbits(32) for _ in int_case["values"]] == int_case["values"]

    text_case = VECTORS["random"]["text_seed_stream"]
    rng = random.Random(text_case["seed"])
    assert [rng.getrandbits(32) for _ in text_case["values"]] == text_case["values"]

    for case in VECTORS["random"]["shuffle"]:
        values = list(case["values"])
        random.Random(int(case["seed"])).shuffle(values)
        assert values == case["expected"], case["seed"]

    for case in VECTORS["random"]["sample"]:
        rng = random.Random(int(case["seed"]))
        assert rng.sample(range(int(case["n"])), int(case["k"])) == case["expected"]


def test_word_scramble_rules_match_the_vectors() -> None:
    vectors = VECTORS["word_scramble"]
    constants = vectors["constants"]
    assert constants["game_id"] == ws.GAME_ID
    assert constants["rounds"] == ws.ROUNDS
    assert constants["round_seconds"] == ws.ROUND_SECONDS
    assert constants["deadline_grace_seconds"] == ws.DEADLINE_GRACE_SECONDS
    assert constants["max_attempts"] == ws.MAX_ATTEMPTS
    assert constants["hint_cost"] == ws.HINT_COST
    assert constants["base_points"] == ws.BASE_POINTS
    assert constants["max_time_bonus"] == ws.MAX_TIME_BONUS
    assert constants["min_items_per_pack"] == ws.MIN_ITEMS_PER_PACK

    for case in vectors["time_bonus"]:
        assert ws.time_bonus(float(case["elapsed_seconds"])) == case["bonus"]

    for case in vectors["round_score"]:
        assert (
            ws.round_score(
                elapsed_seconds=float(case["elapsed_seconds"]),
                used_hint=bool(case["used_hint"]),
                attempt=int(case["attempt"]),
            )
            == case["score"]
        )

    item = ws.Item(
        id="item-stone",
        answer="stone",
        alt_answers=("stoun", "Stones"),
        clue="Hard and grey.",
        clue_image_key="img/stone",
        clue_audio_key=None,
        difficulty=1,
    )
    for case in vectors["correctness"]:
        assert ws.is_correct(item, str(case["value"])) is case["correct"]

    for case in vectors["revelation"]:
        assert ws.revelation(str(case["answer"])) == case["first"]

    for case in vectors["scramble"]:
        rng = random.Random(int(case["seed"]))
        assert ws.scramble(str(case["answer"]), rng) == case["letters"], case["seed"]

    for case in vectors["build_rounds"]:
        items = [
            ws.Item(
                id=str(entry["id"]),
                answer=str(entry["answer"]),
                alt_answers=tuple(str(alt) for alt in entry["alt_answers"]),
                clue=entry["clue"],
                clue_image_key=entry["clue_image_key"],
                clue_audio_key=entry["clue_audio_key"],
                difficulty=int(entry["difficulty"]),
            )
            for entry in case["items"]
        ]
        rounds = ws.build_rounds(items, random.Random(int(case["seed"])))
        assert [
            {
                "item_id": str(round_["item_id"]),
                "letters": str(round_["letters"]),
                "clue": round_["clue"],
            }
            for round_ in rounds
        ] == case["expected"], case["name"]

    start_case = vectors["deadline"][0]
    started = dt.datetime.fromisoformat(start_case["started_at"])
    assert int(ws.deadline(started).timestamp() * 1000) == start_case["deadline_ms"]
    for case in vectors["deadline"][1:]:
        started = dt.datetime.fromisoformat(case["started_at"])
        now = dt.datetime.fromtimestamp(case["now_ms"] / 1000, tz=dt.UTC)
        assert ws.is_late(started, now) is case["is_late"], case["name"]


def test_number_guess_rules_match_the_vectors() -> None:
    vectors = VECTORS["number_guess"]
    constants = vectors["constants"]
    assert constants["game_id"] == guessing.GAME_ID
    assert constants["rounds"] == guessing.ROUNDS
    assert constants["round_seconds"] == guessing.ROUND_SECONDS
    assert constants["deadline_grace_seconds"] == guessing.DEADLINE_GRACE_SECONDS
    assert constants["min_solved"] == guessing.MIN_SOLVED
    assert constants["max_points_per_number"] == guessing.MAX_POINTS_PER_NUMBER

    for case in vectors["levels"]:
        level = guessing.level_for(int(case["difficulty"]))
        assert [level.low, level.high, level.tries] == [case["low"], case["high"], case["tries"]]

    for difficulty, expected in vectors["rounds_for"].items():
        assert guessing.rounds_for(int(difficulty)) == expected

    for case in vectors["secrets"]:
        assert (
            guessing.secret_for(int(case["seed"]), int(case["index"]), int(case["difficulty"]))
            == case["secret"]
        ), case

    for case in vectors["scores"]:
        assert (
            guessing.score_for(attempt=int(case["attempt"]), tries=int(case["tries"]))
            == case["score"]
        )

    for case in vectors["compare"]:
        assert guessing.compare(int(case["secret"]), int(case["guess"])) == case["verdict"]

    for case in vectors["in_range"]:
        level = guessing.level_for(int(case["difficulty"]))
        assert guessing.in_range(int(case["value"]), level) is case["allowed"]

    for case in vectors["narrow"]:
        assert list(
            guessing.narrow(
                int(case["low"]),
                int(case["high"]),
                int(case["guess"]),
                str(case["feedback"]),
            )
        ) == [case["expected_low"], case["expected_high"]]

    for case in vectors["feedback"]:
        assert guessing.feedback_sentence(str(case["code"])) == case["sentence"]

    for case in vectors["heat"]:
        level = guessing.level_for(int(case["difficulty"]))
        assert (
            guessing.heat_for(int(case["secret"]), int(case["guess"]), level) == case["heat"]
        ), case

    assert guessing.HEAT_DIFFICULTY == vectors["heat_difficulty"]

    start_case = vectors["deadline"][0]
    started = dt.datetime.fromisoformat(start_case["started_at"])
    assert int(guessing.deadline(started).timestamp() * 1000) == start_case["deadline_ms"]
    for case in vectors["deadline"][1:]:
        started = dt.datetime.fromisoformat(case["started_at"])
        now = dt.datetime.fromtimestamp(case["now_ms"] / 1000, tz=dt.UTC)
        assert guessing.is_late(started, now) is case["is_late"], case["name"]
