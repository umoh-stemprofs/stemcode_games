#!/usr/bin/env node
/**
 * Regenerate api/requirements.lock.txt (P11-T02).
 *
 * The lock exists so CI installs the same tree that was audited and tested,
 * instead of whatever `>=` resolves to on the day. Resolution happens for the
 * Python version CI uses, and pip reports it without installing anything.
 *
 * Run: npm run lock:api
 */
import { spawnSync } from "node:child_process";
import { existsSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const isWindows = process.platform === "win32";
const venvPython = join(root, ".venv", isWindows ? "Scripts/python.exe" : "bin/python3");
const python = existsSync(venvPython) ? venvPython : isWindows ? "python" : "python3";

// CI runs 3.12; a lock resolved on the contributor's newer interpreter can
// pick wheels CI cannot install.
const CI_PYTHON = "3.12";
const scratch = mkdtempSync(join(tmpdir(), "stem-lock-"));
const report = join(scratch, "report.json");

try {
  const resolveRun = spawnSync(
    python,
    [
      "-m",
      "pip",
      "install",
      "--dry-run",
      "--ignore-installed",
      "--quiet",
      "--report",
      report,
      "--python-version",
      CI_PYTHON,
      "--only-binary=:all:",
      "--target",
      join(scratch, "target"),
      "-r",
      "api/requirements-dev.txt",
    ],
    {
      cwd: root,
      stdio: "inherit",
      env: {
        ...process.env,
        PYTHONPATH: join(root, "api"),
        PYTHONUTF8: "1",
        PYTHONIOENCODING: "utf-8",
      },
    },
  );
  if (resolveRun.status !== 0) {
    console.error("[lock] resolution failed; the lock was not written.");
    process.exit(resolveRun.status ?? 1);
  }

  const installs = JSON.parse(readFileSync(report, "utf8")).install ?? [];
  // pip/setuptools/wheel are the installer itself, not the application; pinning
  // them in an install file makes `pip install -r` fight its own version.
  const SKIP = new Set(["pip", "setuptools", "wheel"]);
  const lines = installs
    .filter((entry) => !SKIP.has(entry.metadata.name.toLowerCase()))
    .map((entry) => `${entry.metadata.name}==${entry.metadata.version}`)
    .sort((a, b) => a.localeCompare(b, "en", { sensitivity: "base" }));

  const body = [
    "# Generated by `npm run lock:api` — do not edit by hand (P11-T02).",
    `# Resolved from api/requirements-dev.txt for Python ${CI_PYTHON}.`,
    "# CI installs this file, then audits it; change a pin above and regenerate.",
    "",
    ...lines,
    "",
  ].join("\n");

  writeFileSync(join(root, "api", "requirements.lock.txt"), body, "utf8");
  console.log(`[lock] wrote api/requirements.lock.txt (${lines.length} packages)`);
} finally {
  rmSync(scratch, { recursive: true, force: true });
}
